const displayNames = new Intl.DisplayNames(['en'], {
  type: 'language',
});

export const languages: LanguageOption[] = languageCodes
  .map((value) => ({
    label: displayNames.of(value) ?? value,
    value,
  }))
  .sort((left, right) => left.label.localeCompare(right.label));

export const defaultLanguage: LanguageOption =
  languages.find(({ value }) => value === 'en') ?? {
    label: 'English',
    value: 'en',
  };
